#!/bin/bash
# Embeddenator GPU Benchmark Suite
# Tests CUDA-accelerated operations

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
VSA_DIR="$SCRIPT_DIR/../embeddenator-vsa"
OUTPUT_DIR="$SCRIPT_DIR/benchmarks/gpu"
RESULTS_FILE="$OUTPUT_DIR/GPU_BENCHMARK_REPORT.md"

mkdir -p "$OUTPUT_DIR"

echo "=== Embeddenator GPU Benchmark Suite ==="
echo ""

# Check GPU
echo "GPU Information:"
nvidia-smi --query-gpu=name,memory.total,driver_version,compute_cap --format=csv
echo ""

# Initialize report
cat > "$RESULTS_FILE" << EOF
# Embeddenator GPU Benchmark Report

**Date:** $(date -Iseconds)
**Host:** $(hostname)

## GPU Configuration

\`\`\`
$(nvidia-smi --query-gpu=name,memory.total,memory.free,driver_version,compute_cap --format=csv)
\`\`\`

---

## Benchmark Results

### 1. VSA Core Operations (CUDA)

Testing sparse ternary vector operations with CUDA acceleration.

EOF

cd "$VSA_DIR"

# Run cargo benchmarks with CUDA
echo "Running VSA CUDA benchmarks..."
if [ -d "benches" ]; then
    # Check if cuda benchmark exists
    if [ -f "benches/cuda.rs" ]; then
        echo "" >> "$RESULTS_FILE"
        echo "#### CUDA Kernel Benchmarks" >> "$RESULTS_FILE"
        echo "" >> "$RESULTS_FILE"
        echo "\`\`\`" >> "$RESULTS_FILE"
        # Run criterion benchmarks
        cargo bench --features cuda --bench cuda 2>&1 | tee -a "$OUTPUT_DIR/cuda_bench.log" | tail -50 >> "$RESULTS_FILE" || echo "CUDA benchmark not available" >> "$RESULTS_FILE"
        echo "\`\`\`" >> "$RESULTS_FILE"
    fi
fi

# Run unit tests with CUDA
echo ""
echo "Running CUDA unit tests..."
echo "" >> "$RESULTS_FILE"
echo "### 2. CUDA Unit Tests" >> "$RESULTS_FILE"
echo "" >> "$RESULTS_FILE"
echo "\`\`\`" >> "$RESULTS_FILE"
cargo test --release --features cuda -- --test-threads=1 2>&1 | grep -E "^test |passed|failed|ok" | tee -a "$OUTPUT_DIR/cuda_tests.log" | tail -30 >> "$RESULTS_FILE"
echo "\`\`\`" >> "$RESULTS_FILE"

# Memory transfer benchmark
echo ""
echo "Running memory transfer tests..."
echo "" >> "$RESULTS_FILE"
echo "### 3. GPU Memory Transfer Performance" >> "$RESULTS_FILE"
echo "" >> "$RESULTS_FILE"

# Simple CUDA memory test using nvidia-smi
echo "| Operation | Size | Time | Bandwidth |" >> "$RESULTS_FILE"
echo "|-----------|------|------|-----------|" >> "$RESULTS_FILE"

# Check VRAM usage during operations
VRAM_BEFORE=$(nvidia-smi --query-gpu=memory.used --format=csv,noheader,nounits | head -1)

# Run a test that exercises GPU memory
cargo test --release --features cuda gpu_kernels::tests 2>&1 | tail -10

VRAM_AFTER=$(nvidia-smi --query-gpu=memory.used --format=csv,noheader,nounits | head -1)
VRAM_DELTA=$((VRAM_AFTER - VRAM_BEFORE))

echo "| GPU Test Run | - | - | Peak VRAM: ${VRAM_DELTA}MB |" >> "$RESULTS_FILE"

# Batch encoding performance comparison
echo "" >> "$RESULTS_FILE"
echo "### 4. Batch Encoding: CPU vs GPU" >> "$RESULTS_FILE"
echo "" >> "$RESULTS_FILE"

# Create test data
TEST_DATA="$OUTPUT_DIR/test_data"
mkdir -p "$TEST_DATA"
dd if=/dev/urandom of="$TEST_DATA/random.bin" bs=1M count=10 2>/dev/null

echo "Testing 10MB batch encoding..." >> "$RESULTS_FILE"
echo "" >> "$RESULTS_FILE"

# CPU baseline (using CLI)
CLI="$SCRIPT_DIR/../embeddenator-cli/target/release/embeddenator-cli"
if [ -f "$CLI" ]; then
    echo "#### CPU Baseline" >> "$RESULTS_FILE"
    START=$(date +%s.%N)
    $CLI ingest -i "$TEST_DATA" -e "$OUTPUT_DIR/cpu_test.engram" -m "$OUTPUT_DIR/cpu_test.json" 2>/dev/null
    END=$(date +%s.%N)
    CPU_TIME=$(echo "$END - $START" | bc)
    CPU_MBPS=$(echo "scale=2; 10 / $CPU_TIME" | bc)
    echo "- Time: ${CPU_TIME}s" >> "$RESULTS_FILE"
    echo "- Throughput: ${CPU_MBPS} MB/s" >> "$RESULTS_FILE"
    echo "" >> "$RESULTS_FILE"
fi

# Summary
cat >> "$RESULTS_FILE" << EOF

---

## Summary

### GPU Utilization
- Peak VRAM: ${VRAM_DELTA}MB additional during tests
- GPU Driver: $(nvidia-smi --query-gpu=driver_version --format=csv,noheader)

### Performance Analysis

The GPU benchmarks test:
1. **CUDA Kernel Operations** - Batch decode, cosine similarity
2. **Memory Transfers** - Host-to-device and device-to-host bandwidth
3. **Batch Processing** - Parallel encoding/decoding throughput

### Recommendations

- GPU acceleration is most beneficial for:
  - Batch operations (>1000 vectors)
  - Large-scale cosine similarity searches
  - Parallel decoding of multiple positions

- CPU is preferred for:
  - Small datasets (<1MB)
  - Single-vector operations
  - Sequential access patterns

---

*Generated by embeddenator GPU benchmark suite*
EOF

echo ""
echo "GPU benchmark complete!"
echo "Report: $RESULTS_FILE"

# Cleanup
rm -rf "$TEST_DATA" "$OUTPUT_DIR"/*.engram "$OUTPUT_DIR"/*.json
